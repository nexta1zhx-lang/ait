/**
 * **语气预设** —— 后端定义、启动时播种、接口发给前端（用户 2026-10-12：「你直接后端给我预设上去」）。
 *
 * 提示词在库里是**一份份拼起来的**（`ai_docs` kind=predict，按 `sort` 顺序拼）：
 *   · 一份放**正文**（你是谁 / 我只做这一种事 / 我认的形态 / 数据怎么读 / 绝对不做 / 方向）
 *     —— 判断依据，用户自己改；
 *   · 一份放**「# 输出」那一节** —— 只管怎么把话说出来，也就是「语气」。
 *
 * 所以每份预设**只有「# 输出」那一节**：打勾就能用，正文那份一点不用动
 * （「我的 → AI 提示词」里「看拼好的全文」能看到拼装结果）。
 *
 * 三条来路，都是这里这一份：
 *   1. `ensureTonePresets()`（启动时）—— 库里**没有**同名那份就补一份（**关着**的，
 *      绝不覆盖已有的、也不动用户改过的名字）。⚠️ 所以**删掉的预设下次启动会回来**。
 *   2. `GET /api/ai-docs` 把它发给前端 —— 「+ 新建分析预测」的下拉就是这几个。
 *   3. 前端不用自己存一份（原来那份在 `frontend/src/prompt-templates.ts`，已合并到这里）。
 *
 * ⚠️ 预设里的文字是**草稿**：用户定稿的是数据库那一份，改语气改数据库里的。
 */

