/**
 * 启动时播种：库里**没有同名那份**就补一份（**默认不打勾**，绝不覆盖已有的）。
 *
 * ⚠️ 「没有同名」是唯一判据 —— 用户改过名字的那份不会被覆盖；
 *    但**删掉的预设下次启动会回来**（这是「预设」该有的样子）。
 *
 * 返回这次真的补了哪几份（给启动日志用）。
 */
export async function ensureTonePresets(): Promise<string[]> {
  const docs = await listDocs()
  const have = new Set(docs.map(d => `${d.kind}|${d.name}`))
  const added: string[] = []
  for (const p of TONE_PRESETS) {
    if (!p.output.trim()) continue // 「空白」没有内容，不播种
    if (have.has(`predict|${p.name}`)) continue
    const doc = await createDoc({kind: 'predict', name: p.name, content: p.output})
    if (doc.enabled) await updateDoc(doc.id, {enabled: false})
    added.push(p.name)
  }
  return added
}
